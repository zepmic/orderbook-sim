"""The order book: both sides together, with limit order matching."""

from dataclasses import replace
from decimal import Decimal

from .book import BookSide
from .model import Order, OrderType, Side, Trade


class OrderBook:
    """Holds the resting buy and sell orders for one instrument."""

    def __init__(self) -> None:
        self.bids = BookSide(Side.BUY)
        self.asks = BookSide(Side.SELL)
        self._resting_ids: set[int] = set()

    def add_limit(self, order: Order) -> list[Trade]:
        """Match a limit order against the opposite side, then rest what is left.

        Resting orders are matched in price-time priority: the best price on
        the opposite side first, and within a price level the order that
        arrived first. Any quantity that cannot be matched is added to the
        order's own side. Returns the trades generated by the match, if any.
        """
        if order.order_type is not OrderType.LIMIT:
            raise ValueError("only limit orders can be inserted")
        if order.id in self._resting_ids:
            raise ValueError(f"order id {order.id} is already resting on the book")
        opposite = self.asks if order.side is Side.BUY else self.bids
        trades: list[Trade] = []
        remaining = order.qty
        while remaining > 0:
            best_price = opposite.best_price()
            if best_price is None:
                break
            crosses = (
                order.price >= best_price
                if order.side is Side.BUY
                else order.price <= best_price
            )
            if not crosses:
                break
            maker = opposite.peek()
            fill_qty = min(remaining, maker.qty)
            trades.append(
                Trade(
                    price=best_price,
                    qty=fill_qty,
                    taker_order_id=order.id,
                    maker_order_id=maker.id,
                    ts=order.ts,
                )
            )
            opposite.fill_front(fill_qty)
            if fill_qty == maker.qty:
                self._resting_ids.discard(maker.id)
            remaining -= fill_qty
        if remaining > 0:
            resting = order if remaining == order.qty else replace(order, qty=remaining)
            side = self.bids if order.side is Side.BUY else self.asks
            side.add(resting)
            self._resting_ids.add(resting.id)
        return trades

    def best_bid(self) -> int | None:
        """Return the highest resting buy price, or None if there are no bids."""
        return self.bids.best_price()

    def best_ask(self) -> int | None:
        """Return the lowest resting sell price, or None if there are no asks."""
        return self.asks.best_price()

    def spread(self) -> int | None:
        """Return best ask minus best bid, or None if either side is empty."""
        bid, ask = self.best_bid(), self.best_ask()
        if bid is None or ask is None:
            return None
        return ask - bid

    def mid_price(self) -> Decimal | None:
        """Return the average of best bid and best ask, or None if either side is empty."""
        bid, ask = self.best_bid(), self.best_ask()
        if bid is None or ask is None:
            return None
        return Decimal(bid + ask) / 2
